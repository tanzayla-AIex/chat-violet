function card(en, fr, note = "", accept = [], acceptEn = []) {
  if (Array.isArray(note)) {
    acceptEn = Array.isArray(accept) ? accept : [];
    accept = note;
    note = "";
  }
  return { en, fr, note, accept, acceptEn };
}

function sent(fr, en, acceptEn = [], note = "Translate into English") {
  return card(en, fr, note, [], acceptEn);
}

function frenchNumber(n) {
  const ones = ["", "un", "deux", "trois", "quatre", "cinq", "six", "sept", "huit", "neuf"];
  const teens = [
    "dix",
    "onze",
    "douze",
    "treize",
    "quatorze",
    "quinze",
    "seize",
    "dix-sept",
    "dix-huit",
    "dix-neuf",
  ];
  const tens = ["", "", "vingt", "trente", "quarante", "cinquante", "soixante"];
  if (n === 100) return "cent";
  if (n < 10) return ones[n];
  if (n < 20) return teens[n - 10];
  if (n < 70) {
    const t = Math.floor(n / 10);
    const u = n % 10;
    if (u === 0) return tens[t];
    if (u === 1) return `${tens[t]}-et-un`;
    return `${tens[t]}-${ones[u]}`;
  }
  if (n < 80) {
    if (n === 70) return "soixante-dix";
    if (n === 71) return "soixante-et-onze";
    return `soixante-${frenchNumber(n - 60)}`;
  }
  if (n === 80) return "quatre-vingts";
  return `quatre-vingt-${frenchNumber(n - 80)}`;
}

